import { describe, expect, it } from 'vitest';
import { PostgresSqlDumpReader, decodePostgresByteaHex } from './postgres-dump-reader';
import { packBlockPos } from './mapblock-parser';

describe('PostgresSqlDumpReader & Hex Bytea Decoder', () => {
  describe('decodePostgresByteaHex', () => {
    it('decodes standard \\\\x hex strings', () => {
      // 0x1c 0x01 0xff 0x02
      const hex = '\\\\x1c01ff02';
      const bytes = decodePostgresByteaHex(hex);
      expect(bytes.length).toBe(4);
      expect(bytes[0]).toBe(0x1c);
      expect(bytes[1]).toBe(0x01);
      expect(bytes[2]).toBe(0xff);
      expect(bytes[3]).toBe(0x02);
    });

    it('decodes single-slash \\x hex strings', () => {
      const hex = '\\xdeadbeef';
      const bytes = decodePostgresByteaHex(hex);
      expect(bytes.length).toBe(4);
      expect(bytes[0]).toBe(0xde);
      expect(bytes[1]).toBe(0xad);
      expect(bytes[2]).toBe(0xbe);
      expect(bytes[3]).toBe(0xef);
    });

    it('handles quoted and semicolon-terminated SQL strings', () => {
      const hex = "'\\\\x01020304');";
      const bytes = decodePostgresByteaHex(hex);
      expect(bytes.length).toBe(4);
      expect(Array.from(bytes)).toEqual([1, 2, 3, 4]);
    });

    it('handles empty or malformed input gracefully', () => {
      expect(decodePostgresByteaHex('').length).toBe(0);
      expect(decodePostgresByteaHex('\\x').length).toBe(0);
    });
  });

  describe('PostgresSqlDumpReader', () => {
    it('rejects invalid non-SQL files', async () => {
      const file = new File(['Hello world this is not SQL!'], 'random.txt');
      const reader = new PostgresSqlDumpReader(file);
      await expect(reader.init()).rejects.toThrow('does not appear to be a valid PostgreSQL SQL dump');
    });

    it('indexes COPY ... FROM stdin format and extracts MapBlocks in bounds', async () => {
      // Create 3 MapBlocks: (0, 0, 0), (1, 0, 1), and (-2, 0, -2)
      const p1 = packBlockPos(0, 0, 0);
      const p2 = packBlockPos(1, 0, 1);
      const p3 = packBlockPos(-2, 0, -2);

      const sqlContent = [
        '--',
        '-- PostgreSQL database dump',
        '--',
        'CREATE TABLE public.blocks (pos bigint NOT NULL, data bytea);',
        'COPY public.blocks (pos, data) FROM stdin;',
        `${p1}\t\\\\x1c01ffff0202aabb`,
        `${p2}\t\\\\x1c01ffff0202ccdd`,
        `${p3}\t\\\\x1c01ffff0202eeff`,
        '\\.',
        ''
      ].join('\n');

      const file = new File([sqlContent], 'map.sql');
      const reader = new PostgresSqlDumpReader(file);
      await reader.init();

      const overview = await reader.scanOverviewAndVerticalLayers();
      expect(overview.estimatedTotalBlocks).toBe(3);
      expect(overview.minBlockX).toBe(-2);
      expect(overview.maxBlockX).toBe(1);
      expect(overview.minBlockZ).toBe(-2);
      expect(overview.maxBlockZ).toBe(1);
      expect(overview.exploredBlockKeys.has('0,0')).toBe(true);
      expect(overview.exploredBlockKeys.has('1,1')).toBe(true);
      expect(overview.exploredBlockKeys.has('-2,-2')).toBe(true);

      // Query blocks in bounds around origin [-1..1, -1..1]
      const results = await reader.queryBlocksInBounds(-1, 1, -1, 1, -1, 1);
      expect(results.length).toBe(2);

      const block0 = results.find(b => b.x === 0 && b.z === 0);
      expect(block0).toBeDefined();
      expect(block0?.data.length).toBe(8);
      expect(block0?.data[6]).toBe(0xaa);
      expect(block0?.data[7]).toBe(0xbb);

      reader.close();
    });

    it('indexes INSERT INTO format and extracts MapBlocks', async () => {
      const p1 = packBlockPos(5, 10, -5);
      const sqlContent = [
        'CREATE TABLE blocks (pos bigint, data bytea);',
        `INSERT INTO blocks (pos, data) VALUES (${p1}, '\\\\x1c01ffff02029988');`
      ].join('\n');

      const file = new File([sqlContent], 'custom_world.sql');
      const reader = new PostgresSqlDumpReader(file);
      await reader.init();

      const overview = await reader.scanOverviewAndVerticalLayers();
      expect(overview.estimatedTotalBlocks).toBe(1);
      expect(overview.minBlockX).toBe(5);
      expect(overview.maxBlockX).toBe(5);
      expect(overview.minBlockZ).toBe(-5);

      const results = await reader.queryBlocksInBounds(4, 6, -6, -4, 9, 11);
      expect(results.length).toBe(1);
      expect(results[0].x).toBe(5);
      expect(results[0].y).toBe(10);
      expect(results[0].z).toBe(-5);
      expect(results[0].data[6]).toBe(0x99);
      expect(results[0].data[7]).toBe(0x88);

      reader.close();
    });

    it('successfully parses actual sample-luanti-world/map.sql generated by script', async () => {
      const fs = await import('node:fs');
      const path = await import('node:path');
      const sqlPath = path.resolve(process.cwd(), 'sample-luanti-world/map.sql');
      if (!fs.existsSync(sqlPath)) return;

      const sqlBuf = fs.readFileSync(sqlPath);
      const file = new File([sqlBuf], 'map.sql');
      const reader = new PostgresSqlDumpReader(file);
      await reader.init();

      const overview = await reader.scanOverviewAndVerticalLayers();
      expect(overview.estimatedTotalBlocks).toBe(81);
      expect(overview.minBlockX).toBe(-4);
      expect(overview.maxBlockX).toBe(4);
      expect(overview.minBlockZ).toBe(-4);
      expect(overview.maxBlockZ).toBe(4);

      // Query blocks around spawn [0, 0]
      const results = await reader.queryBlocksInBounds(-1, 1, -1, 1, -1, 1);
      expect(results.length).toBe(9); // 3x3 block grid

      reader.close();
    });
  });
});
