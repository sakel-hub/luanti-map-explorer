export function resolveNodeColor(nodeName: string): [number, number, number] {
  if (LUANTI_NODE_COLORS[nodeName]) {
    return LUANTI_NODE_COLORS[nodeName];
  }
  const lower = nodeName.toLowerCase();

  // Strip prefixes for MineClone derivative nodes (stairs, slabs, walls, fences)
  if (lower.startsWith('mcl_stairs:') || lower.startsWith('mcl_walls:') || lower.startsWith('mcl_fences:')) {
    const base = lower.replace(/^mcl_[a-z]+:(stair_|slab_|wall_)?/, '');
    const coreCand = 'mcl_core:' + base;
    if (LUANTI_NODE_COLORS[coreCand]) return LUANTI_NODE_COLORS[coreCand];
  }

  // MineClone namespaces
  if (lower.startsWith('mcl_deepslate:')) return [75, 75, 78];
  if (lower.startsWith('mcl_nether:')) return [111, 54, 52];
  if (lower.startsWith('mcl_end:')) return [218, 222, 161];
  if (lower.startsWith('mcl_sculk:')) return [13, 41, 49];
  if (lower.startsWith('mcl_copper:')) return [192, 107, 79];
  if (lower.startsWith('mcl_amethyst:')) return [132, 92, 185];
  if (lower.startsWith('mcl_blackstone:')) return [40, 36, 42];
  if (lower.startsWith('mcl_crimson:')) return [148, 25, 45];
  if (lower.startsWith('mcl_mud:') || lower.includes('mud')) return [60, 48, 40];
  if (lower.startsWith('mcl_mangrove:') || lower.includes('mangrove')) return [104, 88, 62];
  if (lower.startsWith('mcl_cherry_blossom:')) return [238, 175, 192];

  // Ethereal mod nodes
  if (lower.startsWith('ethereal:')) {
    if (lower.includes('bamboo')) return [130, 167, 76];
    if (lower.includes('crystal')) return [50, 97, 119];
    if (lower.includes('fiery')) return [136, 27, 8];
    if (lower.includes('gray')) return [155, 155, 155];
    if (lower.includes('grove')) return [114, 153, 55];
    if (lower.includes('mushroom')) return [115, 71, 114];
    if (lower.includes('prairie')) return [120, 156, 63];
    if (lower.includes('cold') || lower.includes('frost')) return [128, 165, 97];
    if (lower.includes('sakura')) return [199, 137, 168];
    if (lower.includes('redwood')) return [73, 29, 12];
    if (lower.includes('willow')) return [75, 166, 91];
    if (lower.includes('olive')) return [51, 75, 36];
    if (lower.includes('yellow')) return [123, 140, 63];
    if (lower.includes('banana')) return [150, 133, 99];
    if (lower.includes('marble')) return [98, 133, 181];
  }

  // Water & liquids
  if (lower.includes('mineral_water')) return [32, 178, 196];
  if (lower.includes('water')) return [37, 99, 235];
  if (lower.includes('lava')) return [249, 115, 22];

  // Everness mod
  if (lower.includes('mineral_stone') || lower.includes('mineral_sand') || lower.includes('mineral_waters')) {
    return [222, 208, 192];
  }
  if (lower.includes('cursed')) return [39, 76, 54];
  if (lower.includes('frosted')) return [169, 207, 248];
  if (lower.includes('forsaken_desert')) return [201, 140, 80];
  if (lower.includes('forsaken_tundra')) return [32, 32, 30];
  if (lower.includes('snow') || lower.includes('ice')) return [224, 242, 254];
  if (lower.includes('coral_grass') || lower.includes('coral_leaves') || lower.includes('coral_bush')) {
    return [109, 50, 71];
  }
  if (
    lower.includes('crystal_grass') ||
    lower.includes('crystal_leaves') ||
    lower.includes('crystal_megalith') ||
    lower.includes('crystal_pillar') ||
    lower.includes('crystal_block') ||
    lower.includes('amethyst_crystal')
  ) {
    return [152, 112, 214];
  }
  if (lower.includes('bamboo')) return [74, 182, 68];
  if (lower.includes('lotus_flower')) return [244, 114, 182];
  if (lower.includes('lotus_leaf')) return [52, 168, 96];
  if (lower.includes('dry_grass') || lower.includes('dry_shrub')) return [182, 162, 68];
  if (lower.includes('leaves') || lower.includes('needles') || lower.includes('bush') || lower.includes('fern')) {
    return [46, 138, 52];
  }
  if (lower.includes('grass')) return [65, 111, 26];
  if (lower.includes('sand')) return [198, 193, 144];
  if (lower.includes('chest') || lower.includes('protector') || lower.includes('torch') || lower.includes('mese')) {
    return [250, 204, 21];
  }
  if (lower.includes('brick') || lower.includes('roof') || lower.includes('pot')) return [168, 68, 56];
  if (
    lower.includes('wood') ||
    lower.includes('tree') ||
    lower.includes('plank') ||
    lower.includes('slab') ||
    lower.includes('stair') ||
    lower.includes('log')
  ) {
    return [164, 131, 89];
  }
  // Asuna mods
  if (lower.startsWith('japaneseforest:')) {
    if (lower.includes('leaves')) return [238, 175, 192];
    if (lower.includes('grass')) return [72, 122, 38];
    if (lower.includes('tatami')) return [194, 182, 134];
    if (lower.includes('mud')) return [78, 62, 50];
    if (lower.includes('tree') || lower.includes('wood')) return [142, 94, 72];
    if (lower.includes('brick')) return [68, 62, 60];
  }

  if (lower.startsWith('naturalbiomes:')) {
    if (lower.includes('leaves')) return [44, 92, 48];
    if (lower.includes('trunk') || lower.includes('wood')) return [136, 102, 74];
    if (lower.includes('rock') || lower.includes('stone')) return [138, 138, 142];
    if (lower.includes('beach') || lower.includes('sand')) return [224, 214, 168];
    if (lower.includes('outback')) return [184, 98, 54];
    if (lower.includes('litter')) return [114, 96, 72];
  }

  // Common stone variants (too_many_stones, moreblocks, etc.)
  if (
    lower.includes('andesite') ||
    lower.includes('diorite') ||
    lower.includes('granite') ||
    lower.includes('basalt') ||
    lower.includes('agate') ||
    lower.includes('amber') ||
    lower.includes('amazonite')
  ) {
    if (lower.includes('basalt')) return [58, 58, 62];
    if (lower.includes('andesite')) return [136, 136, 138];
    if (lower.includes('diorite')) return [186, 186, 188];
    if (lower.includes('granite')) return [162, 124, 114];
    if (lower.includes('amber')) return [212, 140, 52];
    if (lower.includes('amazonite')) return [78, 168, 154];
    if (lower.includes('purple')) return [138, 92, 168];
    if (lower.includes('green')) return [82, 138, 92];
    if (lower.includes('red')) return [168, 72, 64];
    return [136, 136, 138];
  }

  if (lower.includes('dirt')) return [134, 96, 67];
  if (lower.includes('stone') || lower.includes('cobble') || lower.includes('rock') || lower.includes('ore')) {
    return [97, 94, 93];
  }

  // Deterministic hash fallback color for custom mod nodes
  let hash = 0;
  for (let i = 0; i < nodeName.length; i++) {
    hash = (hash * 31 + nodeName.charCodeAt(i)) | 0;
  }
  const r = 80 + (Math.abs(hash) & 0x7f);
  const g = 80 + ((Math.abs(hash) >> 7) & 0x7f);
  const b = 80 + ((Math.abs(hash) >> 14) & 0x7f);
  return [r, g, b];
}
